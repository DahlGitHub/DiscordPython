CREATE TABLE IF NOT EXISTS test_data (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    key TEXT UNIQUE NOT NULL,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS riot_accounts (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    puuid TEXT UNIQUE NOT NULL,
    username TEXT NOT NULL,
    tag TEXT NOT NULL,
    region TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bloons_favorite (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    monkey_name TEXT NOT NULL,
    path1 INTEGER NOT NULL,
    path2 INTEGER NOT NULL,
    path3 INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS bloons_key (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    key TEXT NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.lol_match_id (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL  DEFAULT NOW(),
  match_date DATE NULL,
  puuid TEXT NOT NULL,
  CONSTRAINT lol_match_id_pkey PRIMARY KEY (id),
  CONSTRAINT lol_match_id_puuid_fkey FOREIGN KEY (puuid) REFERENCES riot_accounts (puuid)
) TABLESPACE pg_default;